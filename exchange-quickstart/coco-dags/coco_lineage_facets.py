"""
Adds Egeria's egeria_informationSupplyChain run facet to the OpenLineage events of the Coco DAGs' tasks, so that
Egeria's OpenLineage cataloguer tags the lineage it catalogues from them with the information supply chains the task
moves data along.

information_supply_chain is registered as an OpenLineage provider custom run facet function
(AIRFLOW__OPENLINEAGE__CUSTOM_RUN_FACETS in airflow-marquez.yaml), which calls it for every task event.  The chains
come from coco-supply-chains.json, generated by compose-configs/egeria-quickstart/bin/gen-coco-supply-chains.py
from the strategic digital products' dependencies and subscriptions.

The facet (version 1-1-0) lists every chain the task moves data along in iscQualifiedNames, and Egeria creates each
lineage relationship once for each of them.  A task along a single chain also names it in iscQualifiedName, which is
all that version 1-0-0 of the facet - and an Egeria that predates 1-1-0 - understands.  Tasks along a wire that
crosses between chains, or along none (the sensors, the branches, the coco_operations_* simulation and the reporting
subscriptions), get no facet.

This module is not a DAG file: .airflowignore keeps the DAG processor from parsing it.
"""
from __future__ import annotations

import json
from functools import cache
from pathlib import Path
from typing import Optional

import attr
from openlineage.client.facet_v2 import RunFacet

SUPPLY_CHAINS_FILE = Path(__file__).parent / "coco-supply-chains.json"
FACET_NAME = "egeria_informationSupplyChain"


@attr.define
class EgeriaInformationSupplyChainRunFacet(RunFacet):
    """Names the Egeria information supply chains that a run is part of."""

    iscQualifiedNames: list[str]  # noqa: N815
    iscQualifiedName: Optional[str] = None  # noqa: N815

    @staticmethod
    def _get_schema() -> str:
        return ("https://egeria-project.org/openlineage/facets/1-1-0/EgeriaInformationSupplyChainRunFacet.json"
                "#/$defs/EgeriaInformationSupplyChainRunFacet")


@cache
def supply_chains() -> dict[str, dict[str, list[str]]]:
    return json.loads(SUPPLY_CHAINS_FILE.read_text())["tasks"]


def information_supply_chain(task_instance, ti_state) -> dict[str, RunFacet]:
    """The egeria_informationSupplyChain facet for the task, if it moves data along any supply chain."""
    if task_instance is None:
        return {}
    chains = supply_chains().get(task_instance.dag_id, {}).get(task_instance.task_id, [])
    if not chains:
        return {}
    return {FACET_NAME: EgeriaInformationSupplyChainRunFacet(
        iscQualifiedNames=chains, iscQualifiedName=chains[0] if len(chains) == 1 else None)}
