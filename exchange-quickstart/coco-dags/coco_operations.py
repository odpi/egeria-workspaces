def parse_text_time(value: str, us_dates: bool):
    """Return (datetime, rebuild function) for a text date/time, or None."""
    for pattern, fmt in TEXT_DATE_FORMATS:
        if not pattern.match(value):
            continue
        try:
            if fmt is None:
                parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
                sep = value[10]
                has_tz = parsed.tzinfo is not None
                frac = "." in value[19:]
                def rebuild(d, v=value, sep=sep, has_tz=has_tz, frac=frac):
                    text = d.isoformat(sep=sep, timespec="microseconds" if frac else "seconds")
                    if not has_tz:
                        return text
                    return text.replace("+00:00", "Z") if v.endswith("Z") else text
                return parsed, rebuild
            if fmt.startswith("slash"):
                order = "%m/%d/%Y" if us_dates else "%d/%m/%Y"
                if fmt == "slash-time":
                    order += " %H:%M:%S" if value.count(":") == 2 else " %H:%M"
                return datetime.strptime(value, order), lambda d, o=order: d.strftime(o)
            fmt = fmt.replace("{sep}", value[10] if len(value) > 10 else " ")
            return datetime.strptime(value, fmt), lambda d, f=fmt: d.strftime(f)
        except ValueError:
            return None
    return None


def row_times(table: Table, row: dict, us_dates: bool) -> list[datetime]:
    times = []
    for col, value in row.items():
        if value is None:
            continue
        if table.is_time(col):
            times.append(as_datetime(value))
        elif table.type_of(col) in TEXT_TYPES and isinstance(value, str) and TIME_NAME.search(col):
            parsed = parse_text_time(value.strip(), us_dates)
            if parsed:
                times.append(as_datetime(parsed[0]))
    return times


def as_datetime(value) -> datetime:
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=timezone.utc)
    if isinstance(value, date):
        return datetime(value.year, value.month, value.day, 12, tzinfo=timezone.utc)
    return value


def shift(table: Table, row: dict, delta: timedelta, us_dates: bool, keep: set) -> None:
    """Move every date and time in the row by delta."""
    for col, value in list(row.items()):
        if value is None or col in keep:
            continue
        if table.is_time(col):
            if isinstance(value, datetime):
                row[col] = value + delta
            else:
                row[col] = value + timedelta(days=round(delta.total_seconds() / 86400))
        elif table.type_of(col) in TEXT_TYPES and isinstance(value, str) and TIME_NAME.search(col):
            parsed = parse_text_time(value.strip(), us_dates)
            if parsed:
                moved = parsed[0] + (delta if len(value.strip()) > 10 else timedelta(days=round(delta.total_seconds() / 86400)))
                row[col] = parsed[1](moved)


def vary(table: Table, row: dict, keys: set, siblings: list[dict] | None = None) -> None:
    """Vary measures a little.  Codes and statuses are kept as they are in the row copied, because the systems'
    extracts derive other values from them (a closed investigation has a completion date)."""
    for col, value in list(row.items()):
        if col in keys or value is None:
            continue
        kind = table.type_of(col)
        if MEASURE.search(col) and not NOT_MEASURE.search(col):
            factor = random.uniform(0.85, 1.15)
            if kind in INTEGER_TYPES and isinstance(value, int) and not isinstance(value, bool):
                row[col] = max(0, round(value * factor)) if value >= 0 else round(value * factor)
            elif isinstance(value, Decimal):
                exp = value.as_tuple().exponent
                row[col] = (value * Decimal(str(round(factor, 4)))).quantize(Decimal(1).scaleb(exp))
            elif isinstance(value, float):
                row[col] = round(value * factor, 4)


def natural_identifiers(cur, table: Table, rows: list[dict], extra: list[str]) -> list[str]:
    """The text columns that identify a record although they are not its key: every value has a digit, no two
    rows share one, and they are not references to the key of another table in the system."""
    if not hasattr(table, "_natural"):
        cur.execute("""select kcu.table_name, kcu.column_name
                         from information_schema.table_constraints tc
                         join information_schema.key_column_usage kcu
                           on kcu.constraint_schema = tc.constraint_schema and kcu.constraint_name = tc.constraint_name
                        where tc.table_schema = %s and tc.constraint_type = 'PRIMARY KEY' and tc.table_name <> %s""",
                    (table.schema, table.name))
        referenced = set()
        for other, column in cur.fetchall():
            cur.execute(f'select distinct "{column}"::text from "{table.schema}"."{other}"')
            referenced |= {r[0] for r in cur.fetchall()}
        found = []
        for col, meta in table.columns.items():
            if col in table.pk or col in table.unique or meta["type"] not in TEXT_TYPES or not IDENTIFIER.search(col):
                continue
            values = [r[col] for r in rows if r.get(col) is not None]
            if (len(values) >= 2 and len(set(values)) == len(values) and all(re.search(r"\d", str(v)) for v in values)
                    and not referenced & {str(v) for v in values}):
                found.append(col)
        table._natural = found
    return list(dict.fromkeys(table._natural + [c for c in extra if c in table.columns]))


def next_key(cur, table: Table, column: str, current):
    """A new value for a key column that follows the pattern of the existing values."""
    kind = table.type_of(column)
    if kind in INTEGER_TYPES or kind == "numeric":
        cur.execute(f'select coalesce(max("{column}"), 0) + 1 from {table.ident}')
        return cur.fetchone()[0]
    if kind == "uuid":
        return uuid.uuid4()
    text = str(current)
    if re.fullmatch(r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}", text):
        return str(uuid.uuid4())
    limit = table.columns[column]["length"]
    # Count up the last run of digits; if that would make the value too long, try the runs before it
    for run in reversed(list(re.finditer(r"\d+", text))):
        prefix, digits, suffix = text[:run.start()], run.group(), text[run.end():]
        cur.execute(f'select "{column}" from {table.ident} where "{column}" like %s',
                    (prefix.replace("%", r"\%").replace("_", r"\_") + "%",))
        width, highest = len(digits), int(digits)
        pattern = re.compile(re.escape(prefix) + r"(\d+)" + re.escape(suffix) + "$")
        for (other,) in cur.fetchall():
            hit = pattern.match(str(other).rstrip())
            if hit:
                highest = max(highest, int(hit.group(1)))
        value = f"{prefix}{str(highest + 1).zfill(width)}{suffix}"
        if not limit or len(value) <= limit:
            return value
    return None


def insert(cur, table: Table, row: dict, returning: list[str] | None = None):
    names = [c for c in row if not (table.columns[c]["generated"] and c in (returning or []))]
    cols = ", ".join(f'"{c}"' for c in names)
    sql = f"insert into {table.ident} ({cols}) values ({', '.join(['%s'] * len(names))}) on conflict do nothing"
    if returning:
        sql += " returning " + ", ".join(f'"{c}"' for c in returning)
    cur.execute(sql, [Jsonb(row[c]) if isinstance(row[c], (dict, list)) else row[c] for c in names])
    return cur.fetchone() if returning else cur.rowcount


