"""
Coco Pharmaceuticals operations.

Simulates the company going about its business by adding records to its systems' own databases (coco_pharma,
austin_systems and bucharest_systems).  The coco_feed_* DAGs pick each change up and copy it into the digital
products in the Data Sharing Hub, and from there the products' subscriptions deliver it to the systems that need
it - so these DAGs are what keeps data moving along the information supply chains.

What each table does is set by the activity plan in coco-operations/<database>.json, generated by
compose-configs/egeria-quickstart/bin/gen-coco-operations.py from the systems' SQL:

  entity    a new record is made by copying an existing one under a new key - an expense report, a batch, a
            purchase order - and its child tables (lines, steps, approvals) are copied with it
  event     a new row is recorded against an existing record - a status change, a reading, a stock movement
  snapshot  the current state of something is refreshed - stock on hand, an asset's maintenance status
  master, child and inbound tables are not written directly

Copies are shifted in time so that the newest date in the record is the time it is created, keeping the gaps
between its dates; amounts and quantities vary a little and status values are drawn from the table's other
rows.  New keys follow the pattern of the existing ones (RPT-26-0712 is followed by RPT-26-0713).

Data arrives at different speeds, one DAG per cadence:

    coco_operations_fast      every 3 minutes   readings, scans, telemetry, stock movements, quality events
    coco_operations_steady    every 15 minutes  orders, batches, samples, results, shipments, cases
    coco_operations_slow      hourly            expenses, invoices, payments, payroll, approvals
    coco_operations_daily     06:00 every day   qualifications, calibrations, audits, submissions, reviews

and coco_operations_seed runs once, when it is first unpaused, to give every active table thirty days of history
so the products have something to show straight away.  Trigger it again with {"force": true} to add another
thirty days.  Each DAG has one task per system, grouped by estate; each task declares the tables it can write as
Airflow assets, so OpenLineage reports which systems the activity lands in.

To stop the simulation pause the DAGs.  To slow it down or speed it up change CADENCES below, or move tables
between cadences in the plan.
"""
