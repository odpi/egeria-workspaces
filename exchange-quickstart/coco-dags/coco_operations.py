def new_entity(cur, plan: dict, tables: dict, name: str, when: datetime, us_dates: bool) -> int:
    table = tables[name]
    rows = fetch_rows(cur, table)
    if not rows:
        return 0
    source = random.choice(rows)
    row = dict(source)
    key = table.pk[0]
    times = row_times(table, row, us_dates)
    delta = (when - max(times)) if times else timedelta(0)
    generated = table.columns[key]["generated"]
    if not generated:
        new = next_key(cur, table, key, row[key])
        if new is None:
            log.warning("No new key pattern for %s.%s value %r", name, key, row[key])
            return 0
        row[key] = new
    renumber = table.unique + natural_identifiers(cur, table, rows, plan[name].get("new_values", []))
    for col in renumber:
        row[col] = next_key(cur, table, col, row[col]) if row[col] is not None else None
    shift(table, row, delta, us_dates, keep={key})
    vary(table, row, {key, *renumber}, rows)
    if generated:
        row.pop(key)
        created = insert(cur, table, row, returning=[key])
        if not created:
            return 0
        new = created[0]
    elif not insert(cur, table, row):
        return 0
    return 1 + copy_children(cur, plan, tables, name, key, source[key], new, delta, us_dates)


def copy_children(cur, plan: dict, tables: dict, parent_name: str, key: str, old, new, delta: timedelta,
                  us_dates: bool) -> int:
    """Copy a record's details - and theirs - to the new record that was copied from it."""
    count = 0
    for child_name in plan[parent_name].get("children", []):
        child = tables[child_name]
        siblings = fetch_rows(cur, child, f'where "{key}" = %s', (old,))
        if not siblings:
            continue
        renumber = child.unique + natural_identifiers(cur, child, fetch_rows(cur, child),
                                                      plan[child_name].get("new_values", []))
        # A detail keyed within its parent (report, line number) keeps the rest of its key; one with a key of its
        # own (entry_key) needs a new one
        own_key = [] if key in child.pk else [c for c in child.pk if not child.is_time(c)]
        for source in siblings:
            row = dict(source)
            row[key] = new
            for col in renumber + own_key:
                if child.columns[col]["generated"]:
                    row.pop(col, None)
                elif row.get(col) is not None:
                    row[col] = next_key(cur, child, col, row[col])
            shift(child, row, delta, us_dates, keep=set(child.pk) - {c for c in child.pk if child.is_time(c)})
            vary(child, row, set(child.pk) | set(renumber))
            generated = [c for c in own_key if child.columns[c]["generated"]]
            created = insert(cur, child, row, returning=generated or None)
            if not created:
                continue
            count += 1
            grandchildren = plan[child_name].get("children")
            if grandchildren and len(child.pk) == 1:
                child_key = child.pk[0]
                child_new = created[0] if generated else row[child_key]
                count += copy_children(cur, plan, tables, child_name, child_key, source[child_key], child_new,
                                       delta, us_dates)
    return count


def new_detail(cur, plan: dict, tables: dict, name: str, when: datetime, us_dates: bool) -> int:
    """A new detail recorded against an existing record - a stock movement against a lot."""
    table = tables[name]
    rows = fetch_rows(cur, table)
    if not rows:
        return 0
    row = dict(random.choice(rows))
    parent_key = tables[plan[name]["parent"]].pk[0]
    times = row_times(table, row, us_dates)
    delta = (when - max(times)) if times else timedelta(0)
    renumber = table.unique + natural_identifiers(cur, table, rows, plan[name].get("new_values", []))
    for col in renumber + [c for c in table.pk if c != parent_key and not table.is_time(c)]:
        if table.columns[col]["generated"]:
            row.pop(col, None)
        elif row.get(col) is not None:
            row[col] = next_key(cur, table, col, row[col])
    shift(table, row, delta, us_dates, keep=set(table.pk) - {c for c in table.pk if table.is_time(c)})
    vary(table, row, set(table.pk) | set(renumber))
    return insert(cur, table, row) or 0


def new_event(cur, plan: dict, tables: dict, name: str, when: datetime, us_dates: bool) -> int:
    table = tables[name]
    rows = fetch_rows(cur, table)
    if not rows:
        return 0
    row = dict(random.choice(rows))
    time_keys = [c for c in table.pk if table.is_time(c)]
    times = [as_datetime(row[c]) for c in time_keys if row[c] is not None] or row_times(table, row, us_dates)
    delta = (when - max(times)) if times else timedelta(0)
    shift(table, row, delta, us_dates, keep=set(table.pk) - set(time_keys))
    renumber = table.unique + [c for c in plan[name].get("new_values", []) if c in table.columns]
    for col in renumber:
        row[col] = next_key(cur, table, col, row[col]) if row[col] is not None else None
    vary(table, row, set(table.pk) | set(renumber), rows)
    return insert(cur, table, row) or 0


def refresh_snapshot(cur, tables: dict, name: str, when: datetime, us_dates: bool) -> int:
    table = tables[name]
    rows = fetch_rows(cur, table)
    if not rows:
        return 0
    old = random.choice(rows)
    row = dict(old)
    times = row_times(table, {c: v for c, v in row.items() if c not in table.pk}, us_dates)
    delta = (when - max(times)) if times else timedelta(0)
    if delta <= timedelta(0):
        return 0                                   # never move a snapshot back in time
    shift(table, row, delta, us_dates, keep=set(table.pk))
    vary(table, row, set(table.pk) | set(table.unique), rows)
    changed = [c for c in row if c not in table.pk and row[c] != old[c]]
    if not changed:
        return 0
    sets = ", ".join(f'"{c}" = %s' for c in changed)
    where = " and ".join(f'"{c}" = %s' for c in table.pk)
    cur.execute(f"update {table.ident} set {sets} where {where}",
                [Jsonb(row[c]) if isinstance(row[c], (dict, list)) else row[c] for c in changed]
                + [old[c] for c in table.pk])
    return cur.rowcount


def act(cur, plan: dict, tables: dict, name: str, when: datetime, us_dates: bool) -> int:
    activity = plan[name]["activity"]
    cur.execute("savepoint activity")
    try:
        if activity == "entity":
            count = new_entity(cur, plan, tables, name, when, us_dates)
        elif activity == "child":
            count = new_detail(cur, plan, tables, name, when, us_dates)
        elif activity == "event":
            count = new_event(cur, plan, tables, name, when, us_dates)
        else:
            count = refresh_snapshot(cur, tables, name, when, us_dates)
        cur.execute("release savepoint activity")
        return count
    except Exception as error:                     # one bad copy must not stop the rest of the system's activity
        cur.execute("rollback to savepoint activity")
        log.warning("%s %s skipped: %s", activity, name, error)
        return 0


