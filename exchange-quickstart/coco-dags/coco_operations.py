class Table:
    def __init__(self, cur, qualified: str):
        self.qualified = qualified
        self.schema, self.name = qualified.split(".", 1)
        cur.execute("""select column_name, data_type, column_default, is_identity, character_maximum_length
                         from information_schema.columns where table_schema = %s and table_name = %s
                        order by ordinal_position""", (self.schema, self.name))
        self.columns = {}
        for name, data_type, default, identity, length in cur.fetchall():
            self.columns[name] = {"type": data_type, "length": length,
                                  "generated": identity == "YES" or (default or "").startswith("nextval(")}
        cur.execute("""select tc.constraint_type, kcu.column_name
                         from information_schema.table_constraints tc
                         join information_schema.key_column_usage kcu
                           on kcu.constraint_schema = tc.constraint_schema and kcu.constraint_name = tc.constraint_name
                        where tc.table_schema = %s and tc.table_name = %s
                          and tc.constraint_type in ('PRIMARY KEY', 'UNIQUE')
                        order by tc.constraint_name, kcu.ordinal_position""", (self.schema, self.name))
        rows = cur.fetchall()
        self.pk = [c for t, c in rows if t == "PRIMARY KEY"]
        self.unique = [c for t, c in rows if t == "UNIQUE" and c not in self.pk]

    @property
    def ident(self) -> str:
        return f'"{self.schema}"."{self.name}"'

    def type_of(self, column: str) -> str:
        return self.columns[column]["type"]

    def is_time(self, column: str) -> bool:
        return self.type_of(column) in DATE_TYPES


def fetch_rows(cur, table: Table, where: str = "", args: tuple = ()) -> list[dict]:
    cur.execute(f"select * from {table.ident} {where}", args)
    names = [d.name for d in cur.description]
    return [dict(zip(names, r)) for r in cur.fetchall()]


