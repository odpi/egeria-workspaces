def active_tables(plan: dict, cadence: str | None, seed: bool) -> list[str]:
    """The tables that get new activity: every one with a cadence for the seed, else those of this cadence."""
    return [t for t, e in plan.items()
            if e["activity"] in ACTIVE and e.get("cadence") and (seed or e["cadence"] == cadence)]


def tables_written(plan: dict, active: list[str]) -> set[str]:
    """The active tables and every detail table copied with them."""
    written, todo = set(), list(active)
    while todo:
        name = todo.pop()
        if name not in written:
            written.add(name)
            todo.extend(plan[name].get("children", []))
    return written


def operate(database: str, system: str, cadence: str, seed: bool = False, **context) -> None:
    plan = load_plan(database)[system]
    active = active_tables(plan, cadence, seed)
    if seed:
        params = (context.get("dag_run") and context["dag_run"].conf) or {}
        from airflow.sdk import Variable
        marker = f"coco_operations_seeded::{database}.{system}"
        if Variable.get(marker, default=None) and not params.get("force"):
            log.info("%s.%s already has its history (Variable %s); trigger with {\"force\": true} to add more",
                     database, system, marker)
            return
    us_dates = database == "austin_systems"
    now = datetime.now(timezone.utc)
    conn = PostgresHook(postgres_conn_id=database).get_conn()
    written = {}
    try:
        with conn.cursor() as cur:
            needed = tables_written(plan, active) | {plan[t]["parent"] for t in active if plan[t].get("parent")}
            tables = {name: Table(cur, name) for name in needed}
            for name in active:
                if seed:
                    count = CADENCES[plan[name]["cadence"]]["seed_rows"]
                    moments = sorted(now - timedelta(seconds=random.uniform(0, SEED_DAYS * 86400))
                                     for _ in range(count))
                elif random.random() < CADENCES[cadence]["chance"]:
                    moments = [now - timedelta(seconds=random.uniform(0, 60))]
                else:
                    moments = []
                for when in moments:
                    written[name] = written.get(name, 0) + act(cur, plan, tables, name, when, us_dates)
        conn.commit()
    finally:
        conn.close()
    if seed:
        Variable.set(marker, now.isoformat())
    for name, count in sorted(written.items()):
        log.info("%s: %d row(s)", name, count)
    log.info("%s.%s: %d row(s) written to %d table(s)", database, system, sum(written.values()),
             sum(1 for c in written.values() if c))


def build_dag(cadence: str | None) -> DAG:
    seed = cadence is None
    dag_id = "coco_operations_seed" if seed else f"coco_operations_{cadence}"
    with DAG(
        dag_id=dag_id,
        description=("Gives the Coco systems thirty days of operational history." if seed else
                     f"Adds new {cadence} activity to the Coco systems ({CADENCES[cadence]['schedule']})."),
        doc_md=__doc__,
        schedule="@once" if seed else CADENCES[cadence]["schedule"],
        max_active_runs=1,
        start_date=datetime(2026, 10, 1),
        catchup=False,
        is_paused_upon_creation=False,
        tags=["coco", "coco-operations"] + ([] if seed else [cadence]),
        default_args={"retries": 1, "retry_delay": timedelta(minutes=1)},
    ) as dag:
        for database, estate in ESTATES.items():
            plan = load_plan(database)
            with TaskGroup(group_id=database, tooltip=f"{estate} systems"):
                for system, tables in plan.items():
                    active = active_tables(tables, cadence, seed)
                    if not active:
                        continue
                    written = sorted(tables_written(tables, active))
                    PythonOperator(
                        task_id=system,
                        python_callable=operate,
                        op_kwargs={"database": database, "system": system, "cadence": cadence, "seed": seed},
                        outlets=[asset(database, *t.split(".", 1)) for t in written],
                        doc_md=f"{'Seeds' if seed else 'Adds activity to'} `{database}.{system}`: "
                               + ", ".join(f"`{t.split('.', 1)[1]}`" for t in active),
                    )
    return dag


coco_operations_seed = build_dag(None)
for _cadence in CADENCES:
    globals()[f"coco_operations_{_cadence}"] = build_dag(_cadence)
